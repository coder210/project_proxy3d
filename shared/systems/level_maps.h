// 每关敌人数量（按关索引 level-1 取；实际出生数 = min(本表值, 该关 E 格数)）。
// 每值 >= ENEMY_SPAWN_COUNT(2) 保证双类型各出一只，<= WAVE_MAX_ENEMIES。
inline constexpr int LEVEL_ENEMY_COUNT[LEVEL_COUNT] = { 8, 8, 8, 8, 8 };

// 当前使用关卡索引（1 基，钳制到有效范围）。gs.level 由起始关卡/推进决定。
static inline int level_index_for_wave(const GlobalState& gs)
{
    int lv = gs.level;
    if (lv < 1) lv = 1;
    if (lv > LEVEL_COUNT) lv = LEVEL_COUNT;
    return lv;
}

// 由 ASCII 网格解析该关布局（确定性关键：行主序扫描，双端必须同一顺序）。
//  - 对每个 '#' 依扫描序填入 layout.obs[]（顺序固定 → 障碍实体 ID 跨端一致）
//  - walkable：'#' 为 false，其余 true
//  - 收集玩家出生格 P（恰一个，缺失返回 false）与敌人出生格 E 列表（扫描序）
// 格子索引 = gz*PF_GRID_N + gx（与 PathComponent tile 一致）。
// 障碍世界中心映射（纯整数，与 pf_world_to_grid 反推一致）：
//   gx = c-PF_GRID_OFFSET → 格子中心世界 x = gx + 0.5 → PmObstacle.x10 = (gx+0.5)*10
//   = (c - OFFSET + 0.5)*10 = c*10 - (OFFSET*10 - 5)
static bool level_build_layout(int level, PmLayout* out_obs,
                               int& player_cell,           // 出参格子索引，-1=缺失
                               int* enemy_cells, int& enemy_n,
                               int* exit_cell = nullptr)   // 出参出口格子索引，-1=缺失（可空）
{
    player_cell = -1;
    enemy_n = 0;
    if (exit_cell) *exit_cell = -1;
    if (level < 1 || level > LEVEL_COUNT) return false;
    const char* src = LEVEL_SRCS[level - 1];
    if (!src) return false;

    PmLayout L;
    L.count = 0;
    L.seed  = level;   // 每关常量作 seed（si 公式仍确定性）

    // 墙格位图：先生成才把 '#' 记录下来，第二遍做矩形合并（行主序、确定性）。
    bool wall[LEVEL_ROWS][LEVEL_COLS] = {};

    int r = 0, c = 0;
    for (const char* p = src; *p && r < LEVEL_ROWS; ++p) {
        char ch = *p;
        if (ch == '\n') { r++; c = 0; continue; }
        if (c >= LEVEL_COLS) { c++; continue; }   // 忽略行内多余字符（容错）

        if (ch == 'P') {
            // 网格坐标 gx=c、gz=r（0..63），居中世界 x=c-31.5（pf_grid_to_world）。
            // 格子索引 = gz*PF_GRID_N+gx（与 PathComponent / wave_spawn_enemy_range 一致）
            player_cell = r * PF_GRID_N + c;
        } else if (ch == 'X') {
            // 出口（仅一关一个，可通行，不生成障碍 → 不改障碍 ID 顺序）
            if (exit_cell) *exit_cell = r * PF_GRID_N + c;
        } else if (ch == 'E') {
            if (enemy_n < WAVE_MAX_ENEMIES)
                enemy_cells[enemy_n++] = r * PF_GRID_N + c;
        } else if (ch == '#') {
            wall[r][c] = true;   // 只记录，暂不建障碍（合并后用大矩形）
        }
        // 其余字符（'.' 与非法字符）一律视为空地
        c++;
    }

    // 第二遍：贪心矩形合并（水平到底→再垂直扩展），把相邻墙块并成大长方体。
    // 边界整圈会各合成 4 个大长方体；实心块/空心房间也各拆成若干长方形。
    // 纯函数确定性 → 双端解析结果逐位一致，障碍实体 ID 顺序（行主序）不变约束依旧成立。
    for (r = 0; r < LEVEL_ROWS && L.count < PM_MAX_OBS; ++r) {
        for (c = 0; c < LEVEL_COLS; ++c) {
            if (!wall[r][c]) continue;
            // 水平最大连续宽
            int w = 1;
            while (c + w < LEVEL_COLS && wall[r][c + w]) w++;
            // 垂直最大连续高（整宽列全为墙）
            int h = 1;
            while (r + h < LEVEL_ROWS) {
                bool full = true;
                for (int cc = c; cc < c + w; ++cc)
                    if (!wall[r + h][cc]) { full = false; break; }
                if (!full) break;
                h++;
            }
            // 认领这块矩形
            for (int dr = 0; dr < h; ++dr)
                for (int dc = 0; dc < w; ++dc)
                    wall[r + dr][c + dc] = false;

            PmObstacle& o = L.obs[L.count++];
            o.gx0 = c; o.gz0 = r; o.gw = w; o.gh = h;
            // 中心格 = gx0 + gw/2；世界格心 x = (中心-OFFSET)；x10 = (中心-OFFSET)*10
            //   = ((2*gx0+gw)/2 - OFFSET)*10 = (2*gx0+gw-2*OFFSET)*5（纯整数）
            o.x10  = (2 * c + w - 2 * PF_GRID_OFFSET) * 5;
            o.z10  = (2 * r + h - 2 * PF_GRID_OFFSET) * 5;
            o.hx10 = w * 5;          // 半宽 0.5m/格 → 十分之一米
            o.hz10 = h * 5;          // 半深
            o.sy10 = 14;             // 墙高 1.4m
        }
    }

    // walkable：回填合并后障碍的整个覆盖格（镜像 pf_build_walkable 语义），其余默认 true
    for (int i = 0; i < PF_CELLS; i++) L.walkable[i] = true;
    for (int k = 0; k < L.count; k++) {
        const PmObstacle& o = L.obs[k];
        if (o.gx0 < 0 || o.gz0 < 0 || o.gx0 + o.gw > PF_GRID_N || o.gz0 + o.gh > PF_GRID_N)
            continue;
        for (int dr = 0; dr < o.gh; ++dr)
            for (int dc = 0; dc < o.gw; ++dc)
                L.walkable[(o.gz0 + dr) * PF_GRID_N + (o.gx0 + dc)] = false;
    }

    if (out_obs) *out_obs = L;
    return player_cell >= 0 && enemy_n > 0;   // 缺玩家出生格或无可出生敌人 → 无效关卡
}

// 玩家出生点：由关卡 P 标记解析为世界中心坐标（XZ，纯函数，双端逐位一致）。
// 供加入命令/本地注入生成玩家实体用。
static inline void level_player_spawn(int level, fp_t* fx, fp_t* fz)
{
    int player_cell = -1;
    int enemy_cells[WAVE_MAX_ENEMIES];
    int enemy_n = 0;
    PmLayout layout;
    level_build_layout(level, &layout, player_cell, enemy_cells, enemy_n);
    if (player_cell < 0) { *fx = fp_zero(); *fz = fp_zero(); return; }
    *fx = pf_grid_to_world(player_cell % PF_GRID_N);
    *fz = pf_grid_to_world(player_cell / PF_GRID_N);
}

// 出口点：由关卡 X 标记解析为世界中心坐标（XZ，纯函数，双端逐位一致）。
// 供通关后走到出口推进下一关、小地图出口标记用。缺 X 时返回 (0,0)。
static inline void level_exit_position(int level, fp_t* fx, fp_t* fz)
{
    int player_cell = -1;
    int enemy_cells[WAVE_MAX_ENEMIES];
    int enemy_n = 0;
    int exit_cell = -1;
    PmLayout layout;
    level_build_layout(level, &layout, player_cell, enemy_cells, enemy_n, &exit_cell);
    if (exit_cell < 0) { *fx = fp_zero(); *fz = fp_zero(); return; }
    *fx = pf_grid_to_world(exit_cell % PF_GRID_N);
    *fz = pf_grid_to_world(exit_cell / PF_GRID_N);
}
